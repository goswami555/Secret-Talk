-- SecretTalk MVP schema. Run this in Supabase SQL Editor.
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id text not null,
  sender_tag text not null,
  body text not null default '',
  image_url text,
  created_at timestamptz not null default now(),
  constraint message_has_content check (length(body) > 0 or image_url is not null)
);

create index if not exists messages_room_created_idx on public.messages(room_id, created_at);

alter table public.messages enable row level security;

-- The room ID is a high-entropy private invite token. Anyone who has it can read/write that room.
create policy "read messages by room link" on public.messages for select to anon, authenticated using (true);
create policy "send messages by room link" on public.messages for insert to anon, authenticated with check (length(room_id) >= 20 and length(sender_tag) >= 20 and length(body) <= 2000);
create policy "delete own browser messages" on public.messages for delete to anon, authenticated using (length(sender_tag) >= 20);

-- Enable Realtime for live message updates.
alter publication supabase_realtime add table public.messages;

-- Create a public Storage bucket for image attachments (max 5 MB, image MIME types only).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('chat-images', 'chat-images', true, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do nothing;

create policy "anonymous image upload" on storage.objects for insert to anon, authenticated
with check (bucket_id = 'chat-images');
create policy "public image viewing" on storage.objects for select to anon, authenticated
using (bucket_id = 'chat-images');